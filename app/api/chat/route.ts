function normalize(text: string) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[؟?!.,،؛:]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ")
    .replace(/\bتمن\b/g, "ثمن")
    .replace(/\bتمان\b/g, "اثمان")
    .replace(/\bاثمنة\b/g, "اثمان")
    .replace(/\bشنو\b/g, "اش")
    .replace(/\bواش\b/g, "هل");
}

