/* =========================================================
   NORMALIZE
   ========================================================= */

function normalize(text: string) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[؟?!.,،؛:]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ");
}


