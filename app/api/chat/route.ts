export async function POST(req: Request) {
  try {
    const body = await req.json();

    const messages = Array.isArray(body.messages)
      ? body.messages
      : [];

    if (messages.length === 0) {
      return NextResponse.json(
        { error: "Messages are required" },
        { status: 400 }
      );
    }

    const cleanMessages: ChatMessage[] = messages
      .filter(
        (msg: unknown): msg is ChatMessage =>
          typeof msg === "object" &&
          msg !== null &&
          "role" in msg &&
          "text" in msg &&
          typeof (msg as ChatMessage).text === "string" &&
          ((msg as ChatMessage).role === "user" ||
            (msg as ChatMessage).role === "assistant")
      )
      .slice(-20);

    if (cleanMessages.length === 0) {
      return NextResponse.json(
        { error: "Invalid messages" },
        { status: 400 }
      );
    }

    const lastMessage =
      cleanMessages[cleanMessages.length - 1];

    const normalized = normalize(lastMessage.text);

    // =========================
    // السلام
    // =========================

    if (
      normalized === "سلام" ||
      normalized === "السلام عليكم" ||
      normalized === "سلام عليكم" ||
      normalized === "salam" ||
      normalized === "salam 3likom"
    ) {
      return NextResponse.json({
        reply:
          "وعليكم السلام ورحمة الله وبركاته 👋 كيفاش نقدر نعاونك؟",
      });
    }

    // =========================
    // جواب مباشر للمنتجات
    // =========================

    const productReply = getProductReply(lastMessage.text);

    if (productReply) {
      return NextResponse.json({
        reply: productReply,
      });
    }

    // =========================
    // Gemini للأسئلة الأخرى
    // =========================

    const contents = cleanMessages.map((msg) => ({
      role: msg.role === "assistant" ? "model" : "user",
      parts: [
        {
          text: msg.text,
        },
      ],
    }));

    const response = await ai.models.generateContent({
      model: "gemini-3.8-flash",
      contents,
      config: {
        systemInstruction: BOO_ZIYT_KNOWLEDGE,
        temperature: 0.1,
        maxOutputTokens: 300,
      },
    });

    const reply =
      response.text?.trim() ||
      "سمح ليا، ما قدرتش نوجد ليك جواب دابا. عاود حاول من بعد.";

    return NextResponse.json({
      reply,
    });
  } catch (error) {
    console.error("Gemini error:", error);

    return NextResponse.json(
      {
        error: "وقع خطأ أثناء التواصل مع المساعد.",
      },
      { status: 500 }
    );
  }
}
