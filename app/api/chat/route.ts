/* =========================================================
   GEMINI FALLBACK
========================================================= */

async function askGemini(messages: ChatMessage[]) {
  const contents = messages.map((msg) => ({
    role: msg.role === "assistant" ? "model" : "user",
    parts: [{ text: msg.text }],
  }));

  const response = await ai.models.generateContent({
    model: "gemini-3.8-flash",
    contents,
    config: {
      systemInstruction: BOO_ZIYT_KNOWLEDGE,
      temperature: 0.1,
      maxOutputTokens: 700,
    },
  });

  return (
    response.text?.trim() ||
    "نقدر نعاونك فمنتوجات Boo Ziyt، الباقات، المحل، التوصيل وطرق الأداء. شنو بغيتي تعرف بالضبط؟"
  );
}


/* =========================================================
   POST
========================================================= */

export async function POST(req: Request) {
  try {
    const body = await req.json();

    const messages = Array.isArray(body.messages)
      ? body.messages
      : [];

    if (messages.length === 0) {
      return NextResponse.json(
        { reply: "كتب ليا شنو بغيتي تعرف 😊" },
        { status: 200 }
      );
    }

    const cleanMessages: ChatMessage[] = messages
      .filter(
        (msg: any) =>
          msg &&
          (msg.role === "user" || msg.role === "assistant") &&
          typeof msg.text === "string" &&
          msg.text.trim().length > 0
      )
      .slice(-12);

    if (cleanMessages.length === 0) {
      return NextResponse.json(
        { reply: "كتب ليا شنو بغيتي تعرف 😊" },
        { status: 200 }
      );
    }

    const lastMessage =
      cleanMessages[cleanMessages.length - 1].text;

    const normalized = normalize(lastMessage);

    /* =======================================================
       GREETINGS
    ======================================================= */

    if (
      hasAny(normalized, [
        "سلام",
        "السلام عليكم",
        "سلام عليكم",
        "salam",
        "hello",
        "bonjour",
        "اهلا",
        "مرحبا",
      ])
    ) {
      return NextResponse.json({
        reply:
          "وعليكم السلام ورحمة الله وبركاته 👋 مرحبا بيك فـ Boo Ziyt 🌿 شنو بغيتي تعرف؟",
      });
    }

    /* =======================================================
       DIRECT ANSWER
    ======================================================= */

    const directReply = getCatalogReply(lastMessage);

    if (directReply) {
      return NextResponse.json({
        reply: directReply,
      });
    }

    /* =======================================================
       GEMINI FALLBACK
    ======================================================= */

    try {
      const reply = await askGemini(cleanMessages);

      return NextResponse.json({
        reply,
      });
    } catch (geminiError) {
      console.error("Gemini error:", geminiError);

      return NextResponse.json({
        reply:
          "نقدر نعاونك فمنتوجات Boo Ziyt، الباقات، المحل، التوصيل وطرق الأداء. شنو بغيتي تعرف بالضبط؟",
      });
    }
  } catch (error) {
    console.error("Chat API error:", error);

    return NextResponse.json({
      reply:
        "سمح ليا، وقع مشكل دابا. عاود حاول من بعد 😊",
    });
  }
}
