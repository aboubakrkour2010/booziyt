/* =========================================================
   NORMALIZE
========================================================= */

function normalize(text: string) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[؟?!.,،؛:]/g, " ")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/ـ/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function hasAny(text: string, words: string[]) {
  return words.some((word) => text.includes(normalize(word)));
}


